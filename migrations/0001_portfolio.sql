CREATE TABLE IF NOT EXISTS config (id INTEGER PRIMARY KEY CHECK(id=1),content TEXT NOT NULL);
INSERT OR IGNORE INTO config VALUES(1,'{}');
CREATE TABLE IF NOT EXISTS projects (id INTEGER PRIMARY KEY AUTOINCREMENT,content TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS albums (id INTEGER PRIMARY KEY AUTOINCREMENT,content TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, csrf TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_exp ON sessions(expires);
CREATE TABLE IF NOT EXISTS login_attempts (ip TEXT PRIMARY KEY, window INTEGER NOT NULL, attempts INTEGER NOT NULL);
